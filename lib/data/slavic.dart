int _dayOfYear(int m, int d) => DateTime.utc(2001, m, d).difference(DateTime.utc(2001, 1, 1)).inDays;

/// Чертог по дате рождения: последний чертог, начавшийся не позже этой даты (по кругу года).
Chertog chertogOf(DateTime b) {
  final x = _dayOfYear(b.month, (b.month == 2 && b.day == 29) ? 28 : b.day);
  final sorted = [...chertogs]
    ..sort((a, c) => _dayOfYear(a.startMonth, a.startDay) - _dayOfYear(c.startMonth, c.startDay));
  return sorted.lastWhere((c) => _dayOfYear(c.startMonth, c.startDay) <= x, orElse: () => sorted.last);
}

/// Знаки зодиака, чьи даты пересекаются с чертогом.
List<String> zodiacOverlap(Chertog c, int Function(int month, int day) signIndex, List<String> names) {
  final res = <String>[];
  var d = DateTime.utc(2001, c.startMonth, c.startDay);
  final end = DateTime.utc(c.endMonth < c.startMonth ? 2002 : 2001, c.endMonth, c.endDay);
  while (!d.isAfter(end)) {
    final n = names[signIndex(d.month, d.day)];
    if (!res.contains(n)) res.add(n);
    d = d.add(const Duration(days: 1));
  }
  return res;
}
