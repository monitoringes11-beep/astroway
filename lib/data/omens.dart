String _norm(String s) => s.toLowerCase().replaceAll('ё', 'е');

/// Поиск по словарю: слова запроса обрезаются до основы и ищутся в названии
/// и ключевых словах; сортируем по числу совпавших основ.
List<Omen> searchOmens(String query, {String polarity = '', String sphere = ''}) {
  final base = omens.where(
    (o) => (polarity.isEmpty || o.polarity == polarity) && (sphere.isEmpty || o.spheres.contains(sphere)),
  );
  final q = _norm(query.trim());
  if (q.isEmpty) return base.toList();
  final stems = q
      .split(RegExp(r'[\s,.!?]+'))
      .where((w) => w.length >= 3)
      .map((w) => w.substring(0, w.length - 3 < 3 ? (w.length < 3 ? w.length : 3) : w.length - 3))
      .toList();
  int score(Omen o) {
    final hay = _norm('${o.name} ${o.keywords}');
    return stems.where(hay.contains).length;
  }

  final res = base.where((o) => score(o) > 0).toList()..sort((a, b) => score(b) - score(a));
  return res;
}

List<String> omenTaskFor(String dayKey, int Function(String) hash) =>
    omenTasks[hash('${dayKey}omen') % omenTasks.length];
