class Horoscope {
  final String mood, energy, general, love, money, health, advice, color;
  final List<int> numbers;
  final List<String>? week; // по частям недели, только для недельного
  const Horoscope(
    this.mood,
    this.energy,
    this.general,
    this.love,
    this.money,
    this.health,
    this.advice,
    this.color,
    this.numbers,
    this.week,
  );
}

int weekNumber(DateTime d) => DateTime.utc(d.year, d.month, d.day).millisecondsSinceEpoch ~/ 604800000;

Horoscope horoscopeFor(int sign, DateTime date, {bool week = false, bool easy = false}) {
  final t = easy ? _easy : _serious;
  final key = signs[sign].name + (week ? 'w${weekNumber(date)}' : dayKey(date));
  return Horoscope(
    pick(moods, '${key}m'),
    pick(energyTags, '${key}e'),
    pick(t.general, '${key}g'),
    pick(t.love, '${key}love'),
    pick(t.money, '${key}money'),
    pick(t.health, '${key}health'),
    pick(t.advice, '${key}a'),
    pick(luckyColors, '${key}c'),
    [for (var i = 1; i <= 3; i++) stableHash('${key}n$i') % 40 + 1],
    week ? [for (var i = 0; i < 3; i++) '${weekParts[i]}: ${pick(moods, '$key$i').toLowerCase()}'] : null,
  );
}

