/// Восточный Новый год упрощённо считаем 5 февраля, как в макете.
bool beforeEastNewYear(DateTime b) => b.month < 2 || (b.month == 2 && b.day < 5);

int eastIndexOf(DateTime b) {
  final y = beforeEastNewYear(b) ? b.year - 1 : b.year;
  return ((y - 4) % 12 + 12) % 12;
}

List<String> eastBestWith(int a) =>
    _trines.firstWhere((t) => t.contains(a)).where((x) => x != a).map((x) => eastAnimals[x][0]).toList();

// ===== Совместимость по стихиям =====
class Compatibility {
  final String level, text;
  const Compatibility(this.level, this.text);
}

Compatibility compatibility(int a, int b) {
  final ea = a % 4, eb = b % 4;
  final same = ea == eb;
  final friendly = (ea == 0 && eb == 2) || (ea == 2 && eb == 0) || (ea == 1 && eb == 3) || (ea == 3 && eb == 1);
  final level = same
      ? 'Одна стихия: понимаете друг друга с полуслова'
      : friendly
      ? 'Стихии дополняют друг друга'
      : 'Разные стихии: союз через компромисс';
  final body = same
      ? 'Похожие ценности и ритм жизни. Важно не соревноваться и оставлять друг другу пространство.'
      : friendly
      ? 'Один даёт то, чего не хватает другому. Хорошая основа для долгих отношений.'
      : 'Вам будет интересно вместе, но придётся договариваться о темпе и привычках. Различия могут стать вашей силой.';
  return Compatibility(level, '${elementIcons[ea]} ${elements[ea]} и ${elementIcons[eb]} ${elements[eb]}. $body');
}
