import 'daily.dart';
import 'moon.dart';

/// Личный разбор «Луна и Солнце» (вариант B из плана) и мини-задание по фазе (вариант C).

const sunStrengths = [
  'упорство и ответственность',
  'оригинальные идеи',
  'интуиция и сочувствие',
  'смелость и скорость',
  'надёжность и вкус',
  'общение и гибкость',
  'забота и чуткость',
  'яркость и щедрость',
  'точность и порядок',
  'дипломатия и чувство красоты',
  'глубина и сила воли',
  'оптимизм и широкий взгляд',
];

String personalSun(int sign, SunEnergy e) =>
    'Сильная сторона дня — ${sunStrengths[sign]}. ${switch (e) {
      SunEnergy.high => 'Энергии много, используйте её для главного дела.',
      SunEnergy.mid => 'Ровный день, хорошо идёт системная работа.',
      SunEnergy.low => 'Берегите силы и не распыляйтесь.',
    }}';

String personalMoon(MoonPhase p, {required bool easy}) =>
    '${moonText(p, easy: easy)} Лучше не делать: ${switch (p) {
      MoonPhase.newMoon => 'не начинайте спор и не давайте громких обещаний.',
      MoonPhase.young => 'не берите на себя слишком много.',
      MoonPhase.full => 'не принимайте решений на эмоциях.',
      MoonPhase.old => 'не беритесь за новые крупные дела.',
    }}';

/// Совпадает ли ритм дня со стихией знака (индекс % 4: земля, воздух, вода, огонь).
bool rhythmFits(int sign, SunEnergy e, MoonPhase p) {
  final el = sign % 4;
  return (el == 3 && e == SunEnergy.high) ||
      (el == 0 && e != SunEnergy.high) ||
      (el == 1 && e == SunEnergy.mid) ||
      (el == 2 && p != MoonPhase.young);
}

String rhythmText(bool fits) => fits
    ? 'Сегодняшняя энергия совпадает с вашим ритмом: день может пройти легко.'
    : 'Ритм дня немного отличается от вашего: двигайтесь в своём темпе и делайте паузы.';

/// Мини-задание по фазе: [заголовок, задание].
List<String> moonTask(MoonPhase p) => switch (p) {
  MoonPhase.newMoon => [
    'Новолуние — время для новых идей.',
    'Загадайте одно намерение на новый лунный цикл и запишите его.',
  ],
  MoonPhase.young => [
    'Растущая Луна — время набирать силу.',
    'Запишите одно дело, которое хотите вырастить за две недели.',
  ],
  MoonPhase.full => ['Полнолуние — день сильных эмоций.', 'Запишите, что сегодня особенно сильно почувствовали.'],
  MoonPhase.old => ['Убывающая Луна — время отпускать.', 'Выберите одну вещь или мысль, которую готовы отпустить.'],
};
